# Basic Arithmetic Operators

friends = 5

friends += 1 #friends = friends + 1
friends -= 2 #friends = friends - 1
friends *= 3 #friends = friends * 3
friends /= 2 #friends = friends / 2
friends **= 2 #friends = friends ** 2 (friends to the power of 2 or friends^2)
remainder = friends % 3 #modulous

print(friends)
print(remainder) 