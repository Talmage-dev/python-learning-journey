# Basic functions

x = 3.14
y = -4
z = 5

result1 = round(x) #round function, rounds to nearest whole number
result2 = abs(y) #absolute functions, changes to absolute value of variable
result3 = pow(4, 3) #power function, 4 cubed (4 to the power of 3)
result4 = max(x, y, z) #max function, finds the max value
result5 = min(x, y, z) #min function, finds the min value


print(result1)
print(result2)
print(result3)
print(result4)
print(result5)